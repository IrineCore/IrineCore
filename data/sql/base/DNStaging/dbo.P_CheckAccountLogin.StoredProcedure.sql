CREATE PROCEDURE [dbo].[P_CheckAccountLogin]
	  @datBasisDate date --// ?? ??
	, @intAccountID int --// ?? ID
	, @bitLoginFlag bit OUTPUT --// 0=??? ?? ??, 1=??? ?? ??
WITH EXECUTE AS 'SPExecutor'
AS
SET NOCOUNT ON;
SET XACT_ABORT ON;

DECLARE @intReturnValue int;

/**_# Rollback and return if inside an uncommittable transaction.*/
IF XACT_STATE() = -1
BEGIN
	SET @intReturnValue = 1;
	GOTO ErrorHandler;
END

BEGIN TRY
	SET @bitLoginFlag = CASE WHEN EXISTS (SELECT * FROM dbo.DailyUVAccounts WITH (NOLOCK) WHERE BasisDate = @datBasisDate AND AccountID = @intAccountID) THEN 1 ELSE 0 END;
END TRY
BEGIN CATCH
	GOTO ErrorHandler;
END CATCH;

RETURN 0;

ErrorHandler:
IF XACT_STATE() <> 0
	ROLLBACK TRANSACTION;

IF @intReturnValue IS NULL OR @intReturnValue = 0
	EXEC @intReturnValue = dbo.P_AddErrorLog;

RETURN @intReturnValue;
GO
