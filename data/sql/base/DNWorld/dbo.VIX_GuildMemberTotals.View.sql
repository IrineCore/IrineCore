CREATE VIEW [dbo].[VIX_GuildMemberTotals]
WITH SCHEMABINDING AS
SELECT GM.GuildID, COUNT_BIG(*) AS GuildMemberCount
FROM dbo.Guilds G
	INNER JOIN dbo.GuildMembers GM ON G.GuildID = GM.GuildID
WHERE G.CloseFlag = CAST(0 AS bit)
GROUP BY GM.GuildID
GO
