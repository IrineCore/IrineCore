CREATE PROCEDURE [dbo].[P_DelFriend]
	  @inbCharacterID bigint --// ??? ID
	, @vchFriendCharacterIDs varchar(8000) --// ,? ?????? ?? ??? ID ???
--WITH EXECUTE AS 'SPExecutor'
AS
SET NOCOUNT ON;
SET XACT_ABORT ON;

DECLARE @intReturnValue int, @i int;
DECLARE @tblFriendCharacters table (FriendCharacterID bigint NOT NULL PRIMARY KEY);

/**_# Rollback and return if inside an uncommittable transaction.*/
IF XACT_STATE() = -1
BEGIN
	SET @intReturnValue = 1;
	GOTO ErrorHandler;
END

BEGIN TRY
	/**_# ?? ??? ?? ??? ID? ??????.*/
	INSERT @tblFriendCharacters (FriendCharacterID)
	SELECT CAST(string AS bigint)
	FROM dbo.TF_Split(@vchFriendCharacterIDs, ',')
	WHERE string > ''
	OPTION (KEEPFIXED PLAN);

	SET @i = @@ROWCOUNT;
	
	/**_# ?? ??? ?? ??? ??? ?????.*/	
	DELETE dbo.Friends 
	FROM dbo.Friends FR
		INNER JOIN @tblFriendCharacters T ON FR.CharacterID = T.FriendCharacterID
	WHERE (FR.FriendCharacterID = @inbCharacterID AND FR.FriendStatusCode = 3) OR (FR.CharacterID = @inbCharacterID AND FR.FriendStatusCode = 3);
	
	IF @@ROWCOUNT = 0
	BEGIN
		BEGIN TRANSACTION;

		/**_# ?? ???? ???? ?????.*/
		DELETE dbo.Friends
		FROM dbo.Friends FR
			INNER JOIN @tblFriendCharacters T ON FR.FriendCharacterID = T.FriendCharacterID
		WHERE FR.CharacterID = @inbCharacterID;

		/**_# ?? ??? ???? ?? ??? ???? ?? ???? ??? 103135? ?????.*/
		IF @i <> @@ROWCOUNT
		BEGIN
			SET @intReturnValue = 103135;
			GOTO ErrorHandler;
		END	
		
		/**_# ??? ?? ???? FriendStatusCode? Update???(??????).*/
		UPDATE dbo.Friends
		SET FriendStatusCode = 2
		FROM dbo.Friends FR
			INNER JOIN @tblFriendCharacters T ON FR.CharacterID = T.FriendCharacterID
		WHERE FR.FriendCharacterID = @inbCharacterID

		COMMIT TRANSACTION;	
	END 
END TRY
BEGIN CATCH
	GOTO ErrorHandler;
END CATCH;

RETURN 0;

ErrorHandler:
IF XACT_STATE() <> 0
	ROLLBACK TRANSACTION;

IF @intReturnValue IS NULL OR @intReturnValue = 0
	EXEC @intReturnValue = dbo.P_AddErrorLog;

RETURN @intReturnValue;
GO
