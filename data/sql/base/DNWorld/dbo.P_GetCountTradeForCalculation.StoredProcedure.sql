CREATE PROCEDURE [dbo].[P_GetCountTradeForCalculation]
	  @inbCharacterID bigint --// ??? ID
	, @intRecordCount int OUTPUT --// ??? ??? ?
--WITH EXECUTE AS 'SPExecutor'
AS
SET NOCOUNT ON;
SET XACT_ABORT ON;

DECLARE @intReturnValue int;

/**_# Rollback and return if inside an uncommittable transaction.*/
IF XACT_STATE() = -1
BEGIN
	SET @intReturnValue = 1;
	GOTO ErrorHandler;
END

BEGIN TRY
	SELECT @intRecordCount = TradeCount
	FROM dbo.VIX_TradeTotals WITH (NOEXPAND, NOLOCK)
	WHERE CharacterID = @inbCharacterID AND TradeStatusCode = 1;
END TRY
BEGIN CATCH
	GOTO ErrorHandler;
END CATCH;

RETURN 0;

ErrorHandler:
IF XACT_STATE() <> 0
	ROLLBACK TRANSACTION;

IF @intReturnValue IS NULL OR @intReturnValue = 0
	EXEC @intReturnValue = dbo.P_AddErrorLog;

RETURN @intReturnValue;
GO
