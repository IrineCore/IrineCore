END

BEGIN TRY
	/**_# ??? ??? ?? ??? ??? ???? 103250? ?????.*/
	IF (SELECT CAST(AchieveDate AS date) FROM dbo.AchieveMissions WITH (NOLOCK) WHERE CharacterID = @inbCharacterID AND MissionID = @intMissionID)
