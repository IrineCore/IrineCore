ALTER PROCEDURE [dbo].[P_ModCharacterName]
	  @inbCharacterID bigint --// ??? ID
	, @nvcCharacterName nvarchar(30) --// ??? ??
	, @inyCharacterNameChangeCode tinyint = 1 --// 1=??? ??, 2=??? ?? ?? ??? ??
	, @intDeleteWaitingTime int = 10080 --// ??? ?? ?? ??. ?? : minute
	, @intPreviousCharacterNameReservePeriod int = 7 --// ?? ? ??? ??? ???? ??. ?? : day
	, @intPeriodLimit int = 7 --// ?? ?? ?? ????? ?? ?? ??? ??? ?? ??. ?? : day
	, @dt2NextDate datetime2(0) = NULL OUTPUT --// ??? ?? ??? ??? ??.
--WITH EXECUTE AS 'SPExecutor'
AS
SET NOCOUNT ON;
SET XACT_ABORT ON;

DECLARE @intReturnValue int, @nvcCharacterNameBefore nvarchar(30);

/**_# Rollback and return if inside an uncommittable transaction.*/
IF XACT_STATE() = -1
BEGIN
	SET @intReturnValue = 1;
	GOTO ErrorHandler;
END

BEGIN TRY
	/**_# ?? ?? ?? ? ???? ??? ??? ????? ???.*/
	IF EXISTS (
		SELECT *
		FROM dbo.Characters CH WITH (NOLOCK)
			INNER JOIN dbo.DeletedCharacters DC WITH (NOLOCK) ON CH.CharacterID = DC.CharacterID
		WHERE CH.CharacterName = @nvcCharacterName AND DC.DeleteDate < DATEADD(MINUTE, -@intDeleteWaitingTime, GETDATE())
	)
		UPDATE dbo.Characters
		SET CharacterName = NULL
		WHERE CharacterName = @nvcCharacterName;

	/**_## @inyCharacterNameChangeCode ?? 2 ??...*/
	IF @inyCharacterNameChangeCode = 2
	BEGIN
		/**_## ??? ? ?? ??? ???? 101116? ?????.*/
		IF EXISTS (
			SELECT *
			FROM dbo.ForbiddenCharacterNames WITH (NOLOCK)
			WHERE CharacterName = @nvcCharacterName
		)
		BEGIN
			SET @intReturnValue = 101192;
			GOTO ErrorHandler;
		END

		IF EXISTS (
			SELECT *
			FROM dbo.CharacterNameChangeLogs WITH (UPDLOCK)
			WHERE CharacterNameBefore = @nvcCharacterName
				AND ChangeDate > DATEADD(DAY, -@intPreviousCharacterNameReservePeriod, GETDATE())
		)
		BEGIN
			SET @intReturnValue = 101116;
			GOTO ErrorHandler;
		END

		/**_## ??? ??? ??? ??? ??? @intPeriodLimit (day) ??? ???? 101191? ?????.*/
		SELECT TOP (1) @dt2NextDate = DATEADD(DAY, @intPeriodLimit, ChangeDate)
		FROM dbo.CharacterNameChangeLogs WITH (UPDLOCK)
		WHERE CharacterID = @inbCharacterID
		ORDER BY CharacterNameChangeLogID DESC;

		IF @@ROWCOUNT > 0 AND @dt2NextDate > GETDATE()
		BEGIN
			SET @intReturnValue = 101191;
			GOTO ErrorHandler;
		END
	END

	/**_# [Characters] ???? UPDATE???.*/
	/**_## ?? ???? ??? ???? 101116? ?????.*/
	/**_## ?? ??? ???? ???? ??? 101117? ?????.*/
	UPDATE dbo.Characters
	SET @nvcCharacterNameBefore = CharacterName
		, CharacterName = @nvcCharacterName
	WHERE CharacterID = @inbCharacterID;

	IF @@ROWCOUNT = 0
	BEGIN
		SET @intReturnValue = 101117;
		GOTO ErrorHandler;
	END

	/**_# [CharacterNameChangeLogs] ???? INSERT ???.*/
	IF @nvcCharacterNameBefore <> @nvcCharacterName
		INSERT dbo.CharacterNameChangeLogs (CharacterID, CharacterNameBefore, CharacterNameAfter, CharacterNameChangeCode, ChangeDate)
		VALUES (@inbCharacterID, @nvcCharacterNameBefore, @nvcCharacterName, @inyCharacterNameChangeCode, GETDATE());

END TRY
BEGIN CATCH
	IF ERROR_NUMBER() = 2601 AND ERROR_MESSAGE() LIKE N'%IX_UNF_Characters_CharacterName%'
		SET @intReturnValue = 101116;

	GOTO ErrorHandler;
END CATCH;

RETURN 0;

ErrorHandler:
IF XACT_STATE() <> 0
	ROLLBACK TRANSACTION;
IF @intReturnValue IS NULL OR @intReturnValue = 0
	EXEC @intReturnValue = dbo.P_AddErrorLog;

RETURN @intReturnValue;
